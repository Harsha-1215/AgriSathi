const { DataTypes } = require('sequelize');

module.exports = (sequelize) => sequelize.define('MarketplaceProduct', {
  id: { type: DataTypes.UUID, primaryKey: true, defaultValue: DataTypes.UUIDV4 },
  sellerId: { type: DataTypes.STRING(120), allowNull: false },
  categoryId: { type: DataTypes.UUID, allowNull: false },
  productName: { type: DataTypes.STRING(200), allowNull: false },
  brand: { type: DataTypes.STRING(160), allowNull: true },
  description: { type: DataTypes.TEXT, allowNull: false },
  unit: { type: DataTypes.STRING(40), allowNull: false },
  price: { type: DataTypes.DECIMAL(12, 2), allowNull: false, validate: { min: 0 } },
  availableQuantity: { type: DataTypes.DECIMAL(12, 3), allowNull: false, validate: { min: 0 } },
  minOrderQuantity: { type: DataTypes.DECIMAL(12, 3), allowNull: false, defaultValue: 1, validate: { min: 0.001 } },
  specifications: { type: DataTypes.JSONB, allowNull: false, defaultValue: {} },
  condition: { type: DataTypes.ENUM('new', 'used', 'refurbished'), allowNull: false, defaultValue: 'new' },
  deliveryAvailable: { type: DataTypes.BOOLEAN, allowNull: false, defaultValue: false },
  pickupAvailable: { type: DataTypes.BOOLEAN, allowNull: false, defaultValue: true },
  pickupLocation: { type: DataTypes.STRING(500), allowNull: true },
  state: { type: DataTypes.STRING(120), allowNull: true },
  district: { type: DataTypes.STRING(120), allowNull: true },
  mandal: { type: DataTypes.STRING(120), allowNull: true },
  village: { type: DataTypes.STRING(120), allowNull: true },
  pinCode: { type: DataTypes.STRING(10), allowNull: true },
  isOrganic: { type: DataTypes.BOOLEAN, allowNull: false, defaultValue: false },
  regulatedProduct: { type: DataTypes.BOOLEAN, allowNull: false, defaultValue: false },
  safetyInformation: { type: DataTypes.TEXT, allowNull: true },
  manufacturer: { type: DataTypes.STRING(200), allowNull: true },
  batchNumber: { type: DataTypes.STRING(100), allowNull: true },
  manufacturedDate: { type: DataTypes.DATEONLY, allowNull: true },
  expiryDate: { type: DataTypes.DATEONLY, allowNull: true },
  availability: { type: DataTypes.ENUM('available', 'out_of_stock', 'unavailable'), allowNull: false, defaultValue: 'available' },
  status: { type: DataTypes.ENUM('pending', 'approved', 'rejected', 'archived'), allowNull: false, defaultValue: 'pending' },
  rejectionReason: { type: DataTypes.STRING(1000), allowNull: true },
  viewCount: { type: DataTypes.INTEGER, allowNull: false, defaultValue: 0 },
}, {
  tableName: 'marketplace_products',
  indexes: [
    { fields: ['status', 'availability', 'createdAt'] },
    { fields: ['categoryId', 'status', 'availability'] },
    { fields: ['sellerId', 'status', 'createdAt'] },
    { fields: ['state', 'district', 'mandal', 'village'] },
    { fields: ['price'] },
  ],
});
