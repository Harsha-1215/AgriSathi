const { DataTypes } = require('sequelize');

module.exports = (sequelize) => sequelize.define('LivestockListing', {
  id: { type: DataTypes.UUID, primaryKey: true, defaultValue: DataTypes.UUIDV4 },
  sellerId: { type: DataTypes.STRING(120), allowNull: false },
  categoryId: { type: DataTypes.UUID, allowNull: false },
  breedId: { type: DataTypes.UUID, allowNull: true },
  listingName: { type: DataTypes.STRING(180), allowNull: false },
  ageMonths: { type: DataTypes.INTEGER, allowNull: false },
  gender: { type: DataTypes.ENUM('female', 'male', 'unknown'), allowNull: false },
  weightKg: { type: DataTypes.DECIMAL(8, 2), allowNull: true },
  color: { type: DataTypes.STRING(100), allowNull: true },
  healthCondition: { type: DataTypes.ENUM('seller_reports_healthy', 'needs_attention', 'unknown'), allowNull: false, defaultValue: 'unknown' },
  vaccinationStatus: { type: DataTypes.ENUM('vaccinated', 'partially_vaccinated', 'not_vaccinated', 'unknown'), allowNull: false, defaultValue: 'unknown' },
  dewormingInformation: { type: DataTypes.STRING(1000), allowNull: true },
  veterinaryCheckupDate: { type: DataTypes.DATEONLY, allowNull: true },
  medicalHistory: { type: DataTypes.TEXT, allowNull: true },
  productionDetails: { type: DataTypes.JSONB, allowNull: false, defaultValue: {} },
  feedingInformation: { type: DataTypes.TEXT, allowNull: true },
  description: { type: DataTypes.TEXT, allowNull: false },
  price: { type: DataTypes.DECIMAL(12, 2), allowNull: false },
  negotiable: { type: DataTypes.BOOLEAN, allowNull: false, defaultValue: false },
  status: { type: DataTypes.ENUM('pending', 'approved', 'rejected', 'archived'), allowNull: false, defaultValue: 'pending' },
  availability: { type: DataTypes.ENUM('available', 'paused', 'sold'), allowNull: false, defaultValue: 'available' },
  rejectionReason: { type: DataTypes.STRING(1000), allowNull: true },
  contactPreference: { type: DataTypes.ENUM('platform', 'phone', 'both'), allowNull: false, defaultValue: 'platform' },
  locationPublic: { type: DataTypes.BOOLEAN, allowNull: false, defaultValue: true },
  state: { type: DataTypes.STRING(100), allowNull: false },
  district: { type: DataTypes.STRING(100), allowNull: false },
  mandal: { type: DataTypes.STRING(100), allowNull: true },
  village: { type: DataTypes.STRING(120), allowNull: true },
  pinCode: { type: DataTypes.STRING(10), allowNull: true },
  pickupAvailable: { type: DataTypes.BOOLEAN, allowNull: false, defaultValue: true },
}, {
  tableName: 'livestock_listings',
  indexes: [
    { fields: ['status', 'availability', 'createdAt'] },
    { fields: ['sellerId', 'status', 'createdAt'] },
    { fields: ['categoryId', 'breedId', 'status'] },
    { fields: ['district', 'mandal', 'village'] },
    { fields: ['price'] },
    { fields: ['ageMonths'] },
  ],
});
