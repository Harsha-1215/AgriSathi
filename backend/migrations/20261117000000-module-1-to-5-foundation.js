function tableName(model) {
  const name = model.getTableName();
  return typeof name === 'string' ? name : name.tableName;
}

async function ensureModelTable(queryInterface, model, transaction, createdTables) {
  const name = tableName(model);
  const tables = await queryInterface.showAllTables({ transaction });
  if (!tables.some((table) => (typeof table === 'string' ? table : table.tableName) === name)) {
    await queryInterface.createTable(name, model.getAttributes(), { transaction });
    createdTables.push(name);
  }
  const existingIndexes = await queryInterface.showIndex(name, { transaction });
  for (const index of model.options.indexes || []) {
    const indexName = index.name || `${name}_${index.fields.join('_')}${index.unique ? '_unique' : ''}`;
    if (existingIndexes.some((existing) => existing.name === indexName)) continue;
    await queryInterface.addIndex(name, index.fields, { ...index, name: indexName, transaction });
  }
}

async function ensureColumns(queryInterface, model, transaction, addedColumns) {
  const name = tableName(model);
  const columns = await queryInterface.describeTable(name, { transaction });
  for (const [field, attribute] of Object.entries(model.getAttributes())) {
    if (columns[field]) continue;
    const definition = { ...attribute };
    delete definition._autoGenerated;
    await queryInterface.addColumn(name, field, definition, { transaction });
    addedColumns.push({ table: name, field });
  }
}

async function ensureEnumValues(queryInterface, model, field, values, transaction) {
  if (queryInterface.sequelize.getDialect() !== 'postgres') return;
  const name = tableName(model);
  const [types] = await queryInterface.sequelize.query(
    `SELECT namespace.nspname AS schema_name, type.typname AS type_name
     FROM pg_attribute AS attribute
     JOIN pg_type AS type ON type.oid = attribute.atttypid
     JOIN pg_class AS relation ON relation.oid = attribute.attrelid
     JOIN pg_namespace AS namespace ON namespace.oid = relation.relnamespace
     WHERE relation.relname = :tableName AND attribute.attname = :fieldName
       AND attribute.attnum > 0 AND NOT attribute.attisdropped`,
    { replacements: { tableName: name, fieldName: field }, transaction },
  );
  const enumType = types[0];
  if (!enumType) return;
  const quoteIdentifier = queryInterface.queryGenerator.quoteIdentifier.bind(queryInterface.queryGenerator);
  const qualifiedType = `${quoteIdentifier(enumType.schema_name)}.${quoteIdentifier(enumType.type_name)}`;
  for (const value of values) {
    await queryInterface.sequelize.query(
      `ALTER TYPE ${qualifiedType} ADD VALUE IF NOT EXISTS ${queryInterface.sequelize.escape(value)}`,
      { transaction },
    );
  }
}

